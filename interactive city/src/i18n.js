const format = (value, variables = {}) =>
  Object.entries(variables).reduce(
    (output, [key, replacement]) => output.replaceAll(`{${key}}`, String(replacement)),
    value,
  );

export const t = (language, key, variables) =>
  format(UI[language]?.[key] || UI.en[key] || key, variables);

export function localizeCity(city, language) {
  if (language !== "lt") return city;
  const translate = (item) => {
    const copy = LT[item.id] || {};
    const translated = { ...item, ...copy };
    if (item.type) translated.type = TYPES_LT[item.type] || item.type;
    if (item.photo) {
      translated.photo = {
        ...item.photo,
        alt: `${copy.name || item.localName || item.name} – nuotrauka`,
      };
    }
    return translated;
  };

  const localized = translate(city);
  localized.districts = city.districts.map((district) => {
    const localizedDistrict = translate(district);
    localizedDistrict.landmarks = district.landmarks.map(translate);
    return localizedDistrict;
  });
  localized.trails = city.trails.map(translate);
  return localized;
}
